package GeometryCalculator.src.com.example.geometry;

public class Rectangle {
    private int length;
    private int width;

    public Rectangle(int length,int width){
        this.length=length;
        this.width=width;
    }

    public int getlength(){
        return length;
    }
    public void setlength (int length){
        this.length=length;
    }
    public int getwidth(){
        return width;
    }
    public void setwidth(int width){
        this.width=width;
    }

    
}
