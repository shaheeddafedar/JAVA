package GeometryCalculator.src.com.example.geometry;

public class Rectangle {
    private int lenght;
    private int width;

    public Rectangle(int lenght,int width){
        this.lenght=lenght;
        this.width=width;
    }

    public int getlenght(){
        return lenght;
    }
    public void setlenght (int lenght){
        this.lenght=lenght;
    }
    public int getwidth(){
        return width;
    }
    public void setwidth(int width){
        this.width=width;
    }

    
}
